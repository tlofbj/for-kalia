"""Make an adapted edition of the built book by applying text replacements.

Usage (after build/convert.py):
    python3 build/adapt.py

Reads alice-in-wonderland.html and writes kalia-in-wonderland.html. Each
replacement must match at least once, so a change to the book that breaks one
fails loudly instead of silently producing a half-adapted edition.
"""
import argparse
import re
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = PROJECT_DIR / "alice-in-wonderland.html"
DEFAULT_OUTPUT = PROJECT_DIR / "kalia-in-wonderland.html"

NAME = "Kaliʻa"  # the ʻokina is U+02BB, not an apostrophe

# (pattern, replacement), applied in order.
REPLACEMENTS = [
    (r"<!-- Generated by build/convert\.py from build/template\.html\. Edit those, not this file\. -->",
     "<!-- Generated by build/adapt.py from alice-in-wonderland.html. Edit the build scripts, not this file. -->"),
    (r'<p class="title-page__author">by Lewis Carroll</p>',
     '<p class="title-page__author">Adapted by Tata Li from Lewis Carroll</p>'),
    # Keep this edition's saved place and settings separate from the original's.
    (r'new LocalStore\("alice-reader"\)', 'new LocalStore("kalia-reader")'),
    (r"\bAlice\b", NAME),
]


def apply_replacements(page, replacements):
    """Apply (pattern, replacement) pairs in order; each must match at least once."""
    for pattern, replacement in replacements:
        page, count = re.subn(pattern, replacement, page)
        if count == 0:
            raise ValueError(f"Replacement pattern not found: {pattern}")
        print(f"{count:>4} × {pattern}")
    return page


def main():
    parser = argparse.ArgumentParser(description="Make the Kaliʻa edition of the built book.")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="the built book")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="where to write the edition")
    args = parser.parse_args()
    page = apply_replacements(args.source.read_text(encoding="utf-8"), REPLACEMENTS)
    args.output.write_text(page, encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
