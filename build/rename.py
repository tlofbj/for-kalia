"""Make Kaliʻa's birthday edition of the book, as a web page and a PDF.

Alice becomes Kaliʻa and the White Rabbit becomes the Overchalant Puppy. Only
names change in the text. The web page is index.html, so it is what the
published site opens; it greets the reader with a birthday note. The PDF is
printed from the same page with its own print styles.

Usage (after build/convert.py):
    python3 build/rename.py

Needs Google Chrome, which prints the page headlessly. The book's web font
(EB Garamond, which includes the ʻokina) loads from Google Fonts, so print
while online.
"""
import argparse
import re
import subprocess
import tempfile
from pathlib import Path

from adapt import PROJECT_DIR, apply_replacements

CHROME = Path("/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")
DEFAULT_SOURCE = PROJECT_DIR / "alice-in-wonderland.html"
DEFAULT_HTML = PROJECT_DIR / "index.html"
DEFAULT_PDF = PROJECT_DIR / "kalia-and-the-overchalant-puppy.pdf"

# (pattern, replacement), applied in order. \s+ catches names that the page
# source wraps across lines.
RENAMES = [
    # Chapter IV's giant puppy becomes a dog first, so the new Puppy is the only one.
    (r"\bpuppy\b", "dog"),
    (r"\b([Aa])\s+White\s+Rabbit\b", r"\1n Overchalant Puppy"),
    (r"\bWhite\s+Rabbit\b", "Overchalant Puppy"),
    (r"\bW\. RABBIT\b", "O. PUPPY"),     # the door plate
    (r"\bRabbit\b", "Puppy"),            # also "Rabbit’s" and "Down the Rabbit-Hole"
    (r"\brabbits\b", "puppies"),
    (r"\brabbit\b", "puppy"),            # also "rabbit-hole"
    (r"\bAlice\b", "Kaliʻa"),            # ʻokina is U+02BB, not an apostrophe
]

# Page housekeeping, not names: mark the file as generated, give this edition
# its own saved place and settings, and switch on the birthday greeting.
PAGE_FIXES = [
    (r'(<meta name="author" content="Lewis Carroll">)',
     r'\1\n  <meta name="greeting-title" content="Happy Birthday Kaliʻa!">'
     r'\n  <meta name="greeting-message" content="Thank you for being my friend! Here is a book, '
     r'I “wrote” for you... Hope you enjoy it!!!">'),
    (r"<!-- Generated by build/convert\.py from build/template\.html\. Edit those, not this file\. -->",
     "<!-- Generated by build/rename.py from alice-in-wonderland.html. Edit the build scripts, not this file. -->"),
    (r'new LocalStore\("alice-reader"\)', 'new LocalStore("kalia-puppy-reader")'),
]

# The gift's own front matter: a title that doesn't give the book away, and
# Tata Li's credit. Applied after RENAMES, so patterns use the new names.
GIFT_DETAILS = [
    (r'<meta name="description" content="[^"]*">',
     '<meta name="description" content="Kaliʻa’s Wondrous Adventure, adapted by Tata Li.">'),
    (r"Kaliʻa’s Adventures <span class=\"title-page__connective\">in</span> Wonderland",
     "Kaliʻa’s Wondrous Adventure"),
    (r"Kaliʻa’s Adventures in Wonderland", "Kaliʻa’s Wondrous Adventure"),  # tab title, toolbar
    (r'<html lang="en">', '<html lang="en" data-style="playful">'),  # cartoon headings, stamp buttons
    (r'<p class="title-page__author">by Lewis Carroll</p>',
     '<p class="title-page__author">Adapted by Tata Li from Lewis Carroll</p>'),
    (r'<p class="title-page__edition">The Millennium Fulcrum Edition 3\.0</p>',
     '<p class="title-page__edition">Adapted from the Millennium Fulcrum Edition 3.0</p>'),
    (r'(<meta name="greeting-message" content="[^"]*">)',
     r'\1\n  <meta name="greeting-signature" content="Best wishes,&#10;Tata&#10;Oct 30, 2026">'
     r'\n  <meta name="greeting-button" content=":D">'),
]

# Anything here after renaming means a form of a name was missed.
LEFTOVERS = re.compile(r"\b(?:Alice|ALICE|[Rr]abbits?|RABBIT|White\s+Puppy)\b")


def rename(page):
    page = apply_replacements(page, RENAMES + PAGE_FIXES + GIFT_DETAILS)
    leftovers = LEFTOVERS.findall(page)
    if leftovers:
        raise ValueError(f"Names left unchanged: {sorted(set(leftovers))}")
    return page


def print_to_pdf(html_path, pdf_path, work_dir):
    """Print with headless Chrome in a throwaway profile, leaving the user's Chrome alone."""
    subprocess.run(
        [
            str(CHROME),
            "--headless",
            f"--user-data-dir={work_dir / 'chrome-profile'}",
            "--no-pdf-header-footer",
            "--virtual-time-budget=15000",  # let web fonts load and scripts settle
            f"--print-to-pdf={pdf_path}",
            html_path.as_uri(),
        ],
        check=True,
        capture_output=True,
    )


def main():
    parser = argparse.ArgumentParser(description="Make the renamed edition as a web page and a PDF.")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="the built book")
    parser.add_argument("--html", type=Path, default=DEFAULT_HTML, help="where to write the web page")
    parser.add_argument("--pdf", type=Path, default=DEFAULT_PDF, help="where to write the PDF")
    args = parser.parse_args()

    html_path = args.html.resolve()
    html_path.write_text(rename(args.source.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"Wrote {args.html}")

    with tempfile.TemporaryDirectory() as tmp:
        print_to_pdf(html_path, args.pdf.resolve(), Path(tmp))
    print(f"Wrote {args.pdf}")


if __name__ == "__main__":
    main()
